// Its declaration includes a data type, variable name, and optional value.
// Example: int age = 10;
// Primitive data types store simple values, such as int, double, char, and boolean.
// Reference data types refer to objects, such as String, arrays, and classes.
// A variable's value can change during program execution, but its declared type cannot.
